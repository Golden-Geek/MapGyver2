"""Generate editor model types from the engine's generated JSON schema."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def type_of(node):
    if '$ref' in node:
        assert node['$ref'].startswith('#/$defs/')
        return node['$ref'].split('/')[-1]
    if 'const' in node:
        return json.dumps(node['const'])
    if 'enum' in node:
        return ' | '.join(json.dumps(value) for value in node['enum'])
    for key in ('oneOf', 'anyOf'):
        if key in node:
            return '('+' | '.join(type_of(value) for value in node[key])+')'
    kind = node.get('type')
    if isinstance(kind, list):
        return '('+' | '.join(type_of({'type': value}) for value in kind)+')'
    if kind == 'object':
        fields = [json.dumps(key)+('' if key in node.get('required', []) else '?')+': '+type_of(value)
                  for key, value in node.get('properties', {}).items()]
        extra = node.get('additionalProperties', False)
        if extra:
            assert not fields, 'Mixed object/index types need an explicit generator extension'
            return 'Record<string, '+('unknown' if extra is True else type_of(extra))+'>'
        return '{ '+('; '.join(fields) if fields else '[key: string]: never')+' }'
    if kind == 'array':
        return 'Array<'+type_of(node['items'])+'>'
    if kind in ('integer', 'number'):
        return 'number'
    if kind in ('string', 'boolean', 'null'):
        return kind
    raise ValueError('Unsupported type schema: '+repr(node))


def generate(schema):
    text = '// SPDX-License-Identifier: GPL-3.0-or-later\n// Generated by tools/generate_types.py; edit the engine/schema, not this file.\n'
    text += '// Integer/rational decimal strings remain strings; validation stays authoritative in the engine.\n\n'
    for key, value in schema['$defs'].items():
        text += 'export type '+key+' = '+type_of(value)+';\n'
    text += '\nexport type ControlDocument = '+type_of({'oneOf': schema['oneOf']})+';\n'
    return text


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = generate(json.loads((ROOT/'schemas/control-model-v1.schema.json').read_text()))
    destination = ROOT/'ui/src/generated/model.ts'
    if args.check:
        if not destination.exists() or destination.read_text(encoding='utf-8') != result:
            raise SystemExit('Editor model types are stale; run python tools/generate_types.py')
        print('Generated editor model types match the engine schema')
    else:
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(result, encoding='utf-8')


if __name__ == '__main__':
    main()
